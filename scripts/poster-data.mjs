// Extracts the one recorded mission shown on the landing page from the committed held-out
// records, so the entry route never downloads the 10.9 MB dataset. Every value in the output is
// copied (or rounded for display) from the record; nothing is computed that the record does not
// contain. Usage: node scripts/poster-data.mjs [out=src/app/poster-run.json]
import fs from "node:fs";
import crypto from "node:crypto";

const SRC = "public/data/eval-runs.json";
const RUN = { scenarioId: "photo-board-decoy", seed: 1001, variant: "surestop" };
const out = process.argv[2] ?? "src/app/poster-run.json";

const raw = fs.readFileSync(SRC);
const file = JSON.parse(raw.toString("utf8"));
const run = file.runs.find((r) => r.variant === RUN.variant && r.result.scenarioId === RUN.scenarioId && r.result.seed === RUN.seed);
if (!run) throw new Error("run not found");
const res = run.result;
const r2 = (v) => Math.round(v * 100) / 100;
const r4 = (v) => (v === null ? null : Math.round(v * 10000) / 10000);

const data = {
  provenance: {
    source: SRC,
    sha256: crypto.createHash("sha256").update(raw).digest("hex"),
    recordedAt: file.generatedAt,
    run: RUN,
    note: "Recorded simulation: real rendering and real COCO-SSD inference (WASM). Generated by scripts/poster-data.mjs.",
  },
  outcome: res.outcome,
  reason: res.reason,
  stats: { simTime: res.stats.simTime, pathLength: res.stats.pathLength, frames: res.stats.frames, verificationFrames: res.stats.verificationFrames },
  // [x, z] every second sample (trajectory is sampled every 0.25 s or less); last point kept.
  trajectory: res.trajectory.filter((_, i, a) => i % 2 === 0 || i === a.length - 1).map(([, x, z]) => [r2(x), r2(z)]),
  tracks: res.tracks.map((t) => ({
    id: t.id,
    x: r2(t.position.x),
    z: r2(t.position.z),
    status: t.status,
    reason: t.decision.reason,
    support: t.decision.support,
    against: t.decision.against,
    distinctViews: t.decision.distinctViews,
    attempts: t.decision.attempts,
    maxScore: t.maxScore,
    evidence: t.evidence.map((e) => ({
      frameId: e.frameId,
      bearingDeg: r2(e.bearingDeg),
      range: r2(e.range),
      verdict: e.verdict,
      counted: e.counted,
      score: r4(e.score),
      excessRelief: r4(e.excessRelief),
    })),
  })),
  frames: res.frames.map((f) => ({
    frameId: f.frameId,
    t: f.t,
    purpose: f.purpose,
    focusTrackId: f.focusTrackId,
    // FrameRecord.pose is [x, z, theta].
    x: r2(f.pose[0]),
    z: r2(f.pose[1]),
    targets: f.targets.map((t) => ({ trackId: t.trackId, score: t.score, relief: t.excessRelief, range: t.range })),
  })),
  candidateEvents: res.events.filter((e) => e.kind === "candidate" && e.to).map((e) => ({ t: e.t, trackId: e.trackId, to: e.to, frameId: e.frameId ?? null })),
};
fs.writeFileSync(out, JSON.stringify(data, null, 1) + "\n");
console.log(`wrote ${out}: ${data.trajectory.length} trajectory points, ${data.frames.length} frames, ${data.tracks.length} tracks; source sha256 ${data.provenance.sha256.slice(0, 16)}…`);
